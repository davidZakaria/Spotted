export function platformInfo(id: Source) {
  return PLATFORMS.find((p) => p.id === id);
}

export function readyPlatforms() {
  return PLATFORMS.filter((p) => p.readyNow);
}

export function connectPlatforms() {
  return PLATFORMS.filter((p) => !p.readyNow);
}

